import { chromium } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { existsSync, mkdirSync, writeFileSync } from 'node:fs'
import assert from 'node:assert/strict'
const base=process.env.BASE || 'http://127.0.0.1:3111'
const brave='/Applications/Brave Browser.app/Contents/MacOS/Brave Browser'
const browser=await chromium.launch({executablePath:process.env.CHROMIUM_PATH || (existsSync(brave)?brave:undefined),headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream','--mute-audio','--autoplay-policy=no-user-gesture-required']})
const report={errors:[],checks:[],accessibility:[]}
mkdirSync('test-results',{recursive:true})
async function pageFor(options={}) {
 const context=await browser.newContext({viewport:{width:1280,height:800},reducedMotion:'reduce',...options})
 const page=await context.newPage()
 page.on('pageerror',e=>report.errors.push(e.message))
 page.on('console',m=>{if(m.type()==='error')report.errors.push(m.text())})
 return page
}
async function audit(page,label) {
 const a=await new AxeBuilder({page}).withTags(['wcag2a','wcag2aa','wcag21a','wcag21aa']).analyze()
 report.accessibility.push({label,violations:a.violations.map(v=>({id:v.id,impact:v.impact,nodes:v.nodes.map(n=>({html:n.html,summary:n.failureSummary}))}))})
 console.log(`A11y ${label}: ${a.violations.length} violations`)
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),`${label}: horizontal overflow`)
}
try {
 const host=await pageFor()
 await host.goto(base,{waitUntil:'domcontentloaded'})
 await audit(host,'desktop home')
 await host.getByLabel('Your name',{exact:true}).fill('Smoke Host')
 await host.getByRole('button',{name:'Add a passcode',exact:true}).click()
 await host.getByLabel('Room passcode',{exact:true}).fill('check-passcode')
 await host.getByRole('button',{name:'Start a call',exact:true}).click()
 await host.getByRole('button',{name:'Join call',exact:true}).waitFor()
 await audit(host,'desktop prejoin')
 const room=new URL(host.url()).searchParams.get('room')
 assert(room,'room code in URL')
 await host.getByRole('button',{name:'Join call',exact:true}).click()
 await host.getByRole('button',{name:'Leave call',exact:true}).waitFor()
 report.checks.push('create protected room and join')
 const guest=await pageFor({viewport:{width:390,height:844},isMobile:true,hasTouch:true})
 await guest.goto(`${base}/?room=${room}`,{waitUntil:'domcontentloaded'})
 await guest.getByLabel('Your name',{exact:true}).fill('Smoke Guest')
 await guest.getByLabel('Passcode',{exact:true}).fill('wrong')
 await guest.getByRole('button',{name:'Join call',exact:true}).click()
 await guest.getByText('Wrong passcode',{exact:false}).waitFor()
 await guest.getByLabel('Passcode',{exact:true}).fill('check-passcode')
 await guest.getByRole('button',{name:'Join call',exact:true}).click()
 await guest.getByRole('button',{name:'Leave call',exact:true}).waitFor()
 await host.waitForFunction(()=>[...window.__pico.engine.pcs.values()].every(pc=>pc.connectionState==='connected'))
 await audit(host,'desktop call')
 await audit(guest,'mobile call')
 report.checks.push('wrong passcode recovery and mobile join')
 for(const [button,title] of [[/^Chat/,'Chat'],[/^People/,'People'],[/^Quality/,'Video quality'],['Encrypted — privacy and security','Privacy & security'],[/^Music/,'Listen together']]) {
  await host.getByRole('button',{name:button}).click()
  await host.getByRole('dialog').waitFor()
  await audit(host,`panel ${title}`)
  await host.keyboard.press('Escape')
  assert.equal(await host.getByRole('dialog').count(),0,`Escape closes ${title}`)
 }
 await host.getByRole('button',{name:/^Chat/}).click()
 await guest.getByRole('button',{name:/^Chat/}).click()
 await host.getByLabel('Chat message',{exact:true}).fill('Production smoke message')
 await guest.getByText('Smoke Host is typing',{exact:true}).waitFor()
 await host.getByRole('button',{name:'Send message',exact:true}).click()
 await guest.getByText('Production smoke message',{exact:true}).waitFor()
 await guest.keyboard.press('Escape');await host.keyboard.press('Escape')
 report.checks.push('chat delivery and keyboard panel dismissal')
 await host.getByRole('button',{name:/^Quality/}).click()
 await host.getByRole('button',{name:/Data Saver/}).click()
 await host.getByRole('switch',{name:'Lite mode',exact:true}).click()
 await host.getByRole('switch',{name:'Lite mode',exact:true}).click()
 await host.keyboard.press('Escape')
 await host.getByRole('button',{name:/^People/}).click()
 await host.getByRole('button',{name:'Lock room',exact:true}).click()
 await host.getByRole('button',{name:'Unlock room',exact:true}).click()
 await host.keyboard.press('Escape')
 report.checks.push('quality preset, lite mode, host lock/unlock')
 await guest.getByRole('button',{name:'Leave call',exact:true}).click()
 await host.waitForFunction(()=>window.__pico.engine.pcs.size===0)
 await host.getByRole('button',{name:'Leave call',exact:true}).click()
 report.checks.push('leave closes peer connections')
 const restricted=await pageFor({viewport:{width:360,height:740}})
 await restricted.addInitScript(()=>{
  Object.defineProperty(Storage.prototype,'getItem',{value(){throw new DOMException('blocked','SecurityError')}})
  Object.defineProperty(Storage.prototype,'setItem',{value(){throw new DOMException('blocked','SecurityError')}})
 })
 await restricted.goto(base,{waitUntil:'domcontentloaded'})
 await restricted.getByLabel('Your name',{exact:true}).fill('Storage blocked')
 await restricted.getByRole('button',{name:'Start a call',exact:true}).click()
 await restricted.getByRole('button',{name:'Join call',exact:true}).click()
 await restricted.getByRole('button',{name:'Leave call',exact:true}).waitFor()
 assert.equal(await restricted.evaluate(()=>window.__pico.engine.localStream.getTracks().every(t=>t.readyState==='live')),true)
 await restricted.getByRole('button',{name:'Leave call',exact:true}).click()
 await audit(restricted,'storage blocked mobile prejoin')
 report.checks.push('restricted browser storage permits join')
 const denied=await pageFor()
 await denied.addInitScript(()=>{navigator.mediaDevices.getUserMedia=async()=>{throw new DOMException('denied','NotAllowedError')}})
 await denied.goto(`${base}/?room=denied-${Date.now()}`,{waitUntil:'domcontentloaded'})
 await denied.getByText(/Microphone and camera access is blocked/).waitFor()
 await denied.getByRole('button',{name:'Join call',exact:true}).click()
 await denied.getByRole('button',{name:'Leave call',exact:true}).waitFor()
 await denied.getByRole('button',{name:'Leave call',exact:true}).click()
 report.checks.push('denied media permissions recover to media-free call')
 assert.equal(report.errors.length,0,JSON.stringify(report.errors))
 report.passed=report.accessibility.every(a=>a.violations.length===0)
 if(!report.passed)process.exitCode=1
} catch(e){report.failure=String(e);process.exitCode=1;console.error(e)}
finally {await browser.close();writeFileSync('test-results/site-smoke.json',JSON.stringify(report,null,2));console.log(JSON.stringify({checks:report.checks,errors:report.errors,failure:report.failure,passed:report.passed}))}
